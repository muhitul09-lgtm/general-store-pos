-- Muhit Food online store tables (same Supabase project as Muhit Store POS)
create table if not exists public.storefront_products (
 id bigint generated by default as identity primary key,
 name text not null,
 category text not null default 'General',
 description text,
 price numeric(12,2) not null default 0 check(price>=0),
 unit text default 'each',
 image text,
 active boolean not null default true,
 stock numeric(12,2) not null default 0,
 updated_at timestamptz not null default now()
);
create table if not exists public.online_orders (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null default now(),
 customer_name text not null,
 phone text not null,
 address text not null,
 fulfilment text not null default 'Delivery',
 payment_method text not null default 'Cash on Delivery',
 notes text,
 items jsonb not null,
 subtotal numeric(12,2) not null,
 status text not null default 'Pending'
);
alter table public.storefront_products enable row level security;
alter table public.online_orders enable row level security;
drop policy if exists "Public can view active storefront products" on public.storefront_products;
create policy "Public can view active storefront products" on public.storefront_products for select to anon, authenticated using (active=true);
drop policy if exists "Public can place online orders" on public.online_orders;
create policy "Public can place online orders" on public.online_orders for insert to anon, authenticated with check (status='Pending');
-- Owners signed into Supabase can manage the catalogue and view/update orders.
drop policy if exists "Signed in users manage storefront products" on public.storefront_products;
create policy "Signed in users manage storefront products" on public.storefront_products for all to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);
drop policy if exists "Signed in users view and update online orders" on public.online_orders;
create policy "Signed in users view and update online orders" on public.online_orders for all to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);
